#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Train GeneSegNet from scratch on MERFISH mouse brain
=====================================================

Training source:
    MERFISH mouse brain S1R1

Training data:
    generated by
    yourpath/GeneSegNet/
    prepare_genesegnet_merfish_brain_train.py

Network input:
    channel 1 = DAPI
    channel 2 = transcript Gaussian heatmap

Ground truth:
    official MERSCOPE cell boundaries, zIndex_3

IMPORTANT:
    - train from scratch
    - NO pretrained model
    - NO UCS / Cellist / ComSeg / ProSeg outputs
    - NO Stereo model
    - NO pancreas model
    - NO NSCLC model

Output:
    yourpath/genesegnet_merfish_brain_train/model/models/
"""

import os
import sys
import glob
import argparse
import subprocess
from datetime import datetime


# ============================================================
# Paths
# ============================================================

GENESEGNET_ROOT = (
    "yourpath/GeneSegNet"
)

GENESEGNET_CODE = os.path.join(
    GENESEGNET_ROOT,
    "GeneSegNet"
)

TRAIN_ENTRY = os.path.join(
    GENESEGNET_CODE,
    "GeneSeg_train.py"
)


DATA_ROOT = (
    "yourpath/"
    "genesegnet_merfish_brain_train"
)

TRAIN_DIR = os.path.join(
    DATA_ROOT,
    "train"
)

VAL_DIR = os.path.join(
    DATA_ROOT,
    "val"
)

TRAIN_SUBDIR = os.path.join(
    TRAIN_DIR,
    "merfish_brain"
)

VAL_SUBDIR = os.path.join(
    VAL_DIR,
    "merfish_brain"
)

MODEL_DIR = os.path.join(
    DATA_ROOT,
    "model"
)


# ============================================================
# Training parameters
# ============================================================

# MERFISH model:
# grayscale DAPI + transcript heatmap
NCHAN = 2

# Architecture used by previous MERFISH GeneSegNet workflow.
RESIDUAL_ON = 1
STYLE_ON = 1
CONCATENATION = 0

# MERFISH mosaic cells are much larger in pixel units than
# the Stereo training cells.
#
# Previous MERFISH GeneSegNet workflow used a large cell scale,
# so use 85 px for this from-scratch MERFISH training.
DIAM_MEAN = 85.0

N_EPOCHS = 300

LEARNING_RATE = 0.001

BATCH_SIZE = 8

SAVE_EVERY = 50

IMG_FILTER = "_image"
MASK_FILTER = "_label"
HEATMAP_FILTER = "_gaumap_all"


SEP = "=" * 78


def P(*args, **kwargs):
    kwargs.setdefault(
        "flush",
        True
    )
    print(
        *args,
        **kwargs
    )


# ============================================================
# GPU selection
# ============================================================

def choose_gpu():

    try:

        text = subprocess.check_output(
            [
                "nvidia-smi",
                "--query-gpu="
                "index,memory.free,utilization.gpu",
                "--format=csv,noheader,nounits"
            ],
            text=True
        )

    except Exception:

        P(
            "WARNING: nvidia-smi unavailable; "
            "letting GeneSegNet select GPU."
        )

        return None


    rows = []

    P(
        "\nGPU status:"
    )


    for line in text.strip().splitlines():

        idx, free, util = [
            x.strip()
            for x in line.split(",")
        ]

        idx = int(idx)
        free = int(free)
        util = int(util)

        rows.append(
            (
                idx,
                free,
                util
            )
        )

        P(
            f"  GPU {idx}: "
            f"{free/1024:.1f} GB free, "
            f"util={util}%"
        )


    if not rows:
        return None


    # prioritize free memory, then lower utilization
    rows.sort(
        key=lambda x:
            (
                x[1],
                -x[2]
            ),
        reverse=True
    )


    gpu = rows[0][0]


    P(
        f"\nSelected physical GPU = "
        f"{gpu}"
    )


    return gpu


# ============================================================
# Dataset integrity
# ============================================================

def count_files(
    root
):

    patterns = {

        "images":
            os.path.join(
                root,
                "images",
                "*_image.*"
            ),

        "labels":
            os.path.join(
                root,
                "labels",
                "*_label.*"
            ),

        "heatmaps":
            os.path.join(
                root,
                "HeatMaps",
                "HeatMap_all",
                "*_gaumap_all.*"
            ),

        "spots":
            os.path.join(
                root,
                "spots",
                "*.csv"
            ),
    }


    out = {}

    for key, pattern in (
        patterns.items()
    ):

        out[key] = len(
            glob.glob(
                pattern
            )
        )


    return out


def check_dataset():

    P()
    P(SEP)
    P(
        "Checking MERFISH GeneSegNet "
        "training dataset"
    )
    P(SEP)


    if not os.path.isfile(
        TRAIN_ENTRY
    ):

        raise FileNotFoundError(
            TRAIN_ENTRY
        )


    expected = {
        "train":
            (
                TRAIN_SUBDIR,
                1000
            ),

        "val":
            (
                VAL_SUBDIR,
                200
            ),
    }


    for split, (
        root,
        expected_n
    ) in expected.items():

        if not os.path.isdir(
            root
        ):

            raise FileNotFoundError(
                "\nTraining data directory "
                "does not exist:\n"
                f"{root}\n\n"
                "Run "
                "prepare_genesegnet_merfish_brain_train.py "
                "first."
            )


        c = count_files(
            root
        )


        P(
            f"\n{split}:"
        )

        for k,v in c.items():

            P(
                f"  {k:9s} = "
                f"{v:,}"
            )


        if (
            c["images"] != expected_n
            or
            c["labels"] != expected_n
            or
            c["heatmaps"] != expected_n
            or
            c["spots"] != expected_n
        ):

            raise RuntimeError(
                f"\n{split} dataset incomplete.\n"
                f"Expected {expected_n} of each type.\n"
                "Do not start training."
            )


    P()
    P(
        "✓ training dataset is complete"
    )


# ============================================================
# Existing weight guard
# ============================================================

def existing_models():

    return sorted(
        glob.glob(
            os.path.join(
                MODEL_DIR,
                "models",
                "GeneSegNet*"
            )
        )
    )


# ============================================================
# Train
# ============================================================

def run_training(
    gpu=None,
    epochs=N_EPOCHS,
    batch_size=BATCH_SIZE
):

    os.makedirs(
        MODEL_DIR,
        exist_ok=True
    )


    before = set(
        existing_models()
    )


    # ========================================================
    # IMPORTANT:
    #
    # train_dir / val_dir / test_dir are parent folders.
    #
    # Gseg_io.load_train_test_data() performs:
    #
    #     os.listdir(train_dir)
    #
    # and then loads each one-level-down dataset folder.
    #
    # Therefore:
    #
    #   TRAIN_DIR = .../train
    #
    # not:
    #
    #   .../train/merfish_brain
    # ========================================================

    cmd = [

        sys.executable,

        TRAIN_ENTRY,

        "--train",

        "--train_dir",
        TRAIN_DIR,

        "--val_dir",
        VAL_DIR,

        # GeneSeg_train.py runs a TEST stage after training.
        # Supplying a real string here avoids the E12.5
        # "os.listdir(path should be string, not list)" failure.
        "--test_dir",
        VAL_DIR,

        "--look_one_level_down",

        "--img_filter",
        IMG_FILTER,

        "--mask_filter",
        MASK_FILTER,

        "--heatmap_filter",
        HEATMAP_FILTER,

        "--all_channels",

        "--chan",
        str(
            NCHAN
        ),

        "--diam_mean",
        str(
            DIAM_MEAN
        ),

        "--n_epochs",
        str(
            epochs
        ),

        "--learning_rate",
        str(
            LEARNING_RATE
        ),

        "--batch_size",
        str(
            batch_size
        ),

        "--residual_on",
        str(
            RESIDUAL_ON
        ),

        "--style_on",
        str(
            STYLE_ON
        ),

        "--concatenation",
        str(
            CONCATENATION
        ),

        "--save_every",
        str(
            SAVE_EVERY
        ),

        "--save_model_dir",
        MODEL_DIR,

        "--use_gpu",

        "--verbose",
    ]


    # No --pretrained_model on purpose.
    #
    # GeneSeg_train.py explicitly converts absent / None
    # pretrained_model to False and trains from scratch.
    # The training code itself also sets pretrained_model=False
    # before constructing the training model.

    env = os.environ.copy()


    if gpu is not None:

        # Hide all GPUs except chosen physical GPU.
        # Inside PyTorch / GeneSegNet it becomes cuda:0.
        env[
            "CUDA_VISIBLE_DEVICES"
        ] = str(
            gpu
        )


    P()
    P(SEP)

    P(
        "GeneSegNet MERFISH mouse-brain "
        "FROM-SCRATCH TRAINING"
    )

    P(SEP)

    P(
        f"train_dir        = "
        f"{TRAIN_DIR}"
    )

    P(
        f"val_dir          = "
        f"{VAL_DIR}"
    )

    P(
        f"test_dir         = "
        f"{VAL_DIR}"
    )

    P(
        f"save_model_dir   = "
        f"{MODEL_DIR}"
    )

    P()
    P(
        f"nchan            = "
        f"{NCHAN}"
    )

    P(
        f"diam_mean        = "
        f"{DIAM_MEAN}"
    )

    P(
        f"epochs           = "
        f"{epochs}"
    )

    P(
        f"learning_rate    = "
        f"{LEARNING_RATE}"
    )

    P(
        f"batch_size       = "
        f"{batch_size}"
    )

    P()
    P(
        f"residual_on      = "
        f"{RESIDUAL_ON}"
    )

    P(
        f"style_on         = "
        f"{STYLE_ON}"
    )

    P(
        f"concatenation    = "
        f"{CONCATENATION}"
    )

    P()
    P(
        "pretrained_model = NONE "
        "(train from scratch)"
    )


    if gpu is not None:

        P(
            f"physical GPU     = "
            f"{gpu}"
        )

        P(
            "GeneSegNet sees  = "
            "cuda:0"
        )


    P()
    P(
        "Command:"
    )

    P(
        " ".join(
            cmd
        )
    )

    P(SEP)


    start = datetime.now()


    rc = subprocess.run(
        cmd,
        cwd=GENESEGNET_CODE,
        env=env
    ).returncode


    end = datetime.now()


    P()
    P(SEP)

    P(
        f"Training process return code = "
        f"{rc}"
    )

    P(
        f"start = "
        f"{start}"
    )

    P(
        f"end   = "
        f"{end}"
    )


    # ========================================================
    # Search for resulting model even if final TEST stage fails.
    #
    # This matters because previously the E12.5 model had
    # already trained and saved successfully before TEST crashed.
    # ========================================================

    after = set(
        existing_models()
    )


    new_models = sorted(
        after - before,
        key=os.path.getmtime
    )


    if not new_models:

        # It is possible that GeneSegNet overwrote an existing
        # same-name model; inspect all models as fallback.
        all_models = existing_models()

        if all_models:

            newest = max(
                all_models,
                key=os.path.getmtime
            )

            new_models = [
                newest
            ]


    if new_models:

        P()
        P(
            "MODEL CANDIDATE(S):"
        )

        for p in new_models:

            P(
                f"  {p}"
            )

            P(
                f"    size = "
                f"{os.path.getsize(p)/1024/1024:.2f} MB"
            )


        newest = max(
            new_models,
            key=os.path.getmtime
        )


        P()
        P(
            "NEWEST MODEL:"
        )

        P(
            newest
        )


        # Save a simple text pointer for the later liver script.
        pointer = os.path.join(
            DATA_ROOT,
            "FINAL_MODEL_PATH.txt"
        )


        with open(
            pointer,
            "w"
        ) as f:

            f.write(
                newest
                + "\n"
            )


        P()
        P(
            f"model pointer saved:"
            f"\n  {pointer}"
        )


    else:

        P()
        P(
            "WARNING:"
            " no GeneSegNet model file found."
        )


    P(SEP)


    if rc != 0:

        P()
        P(
            "The training command exited non-zero."
        )

        P(
            "If the log already contains:"
        )

        P(
            "  >>>> model trained and saved to ..."
        )

        P(
            "then the training itself succeeded and "
            "only the final evaluation stage may have failed."
        )

        P(
            "Send the last ~50 log lines before rerunning."
        )


    return rc


# ============================================================
# Main
# ============================================================

def main():

    ap = argparse.ArgumentParser()


    ap.add_argument(
        "--gpu",
        type=int,
        default=None,
        help=(
            "Physical GPU index. "
            "If omitted, choose GPU with most free memory."
        )
    )


    ap.add_argument(
        "--epochs",
        type=int,
        default=N_EPOCHS
    )


    ap.add_argument(
        "--batch-size",
        type=int,
        default=BATCH_SIZE
    )


    ap.add_argument(
        "--skip-data-check",
        action="store_true"
    )


    args = ap.parse_args()


    if not args.skip_data_check:

        check_dataset()


    if args.gpu is None:

        gpu = choose_gpu()

    else:

        gpu = args.gpu


    sys.exit(
        run_training(
            gpu=gpu,
            epochs=args.epochs,
            batch_size=args.batch_size
        )
    )


if __name__ == "__main__":
    main()